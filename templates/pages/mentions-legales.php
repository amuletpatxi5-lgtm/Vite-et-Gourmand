    <h3>Données collectées et utilisation</h3>
    <p>Lors de la création d'un compte et d'une commande, nous enregistrons vos nom, prénom, adresse email,
       téléphone et adresse postale. Elles servent uniquement à préparer, livrer et suivre vos commandes,
       et à vous envoyer les emails liés à votre compte (bienvenue, confirmation, mot de passe oublié).
       Base légale : l'exécution du contrat qui nous lie.</p>
    <p>Votre mot de passe n'est jamais stocké en clair : seule une empreinte chiffrée (bcrypt) est conservée.
       Les statistiques de ventes ne contiennent aucune donnée personnelle (numéro de commande, menu, montant, date).</p>
    <p>Sur la page d'accueil, un avis publié n'affiche que votre prénom et l'initiale de votre nom.</p>

