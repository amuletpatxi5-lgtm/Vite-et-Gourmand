    <h1>Conditions générales de vente</h1>
    <p class="aide">Projet réalisé dans le cadre d'un examen : entreprise et conditions fictives.</p>

    <h2>1. Objet</h2>
    <p>Les présentes conditions s'appliquent à toute commande de menus passée sur le site Vite &amp; Gourmand
       par un client disposant d'un compte.</p>

    <h2>2. Commande</h2>
    <p>Chaque menu indique un nombre minimum de personnes et un délai de commande à respecter avant la prestation.
       Avant de valider, le client voit le récapitulatif complet du prix. La commande est confirmée par email
       et apparaît dans l'espace « Mes commandes », où son suivi est affiché étape par étape.</p>

    <h2>3. Prix</h2>
    <ul>
        <li>Les prix sont indiqués en euros, par personne.</li>
        <li><strong>Remise de 10 %</strong> sur le prix du menu dès 5 personnes de plus que le minimum du menu.</li>
        <li><strong>Livraison</strong> : gratuite dans Bordeaux ; ailleurs, 5 € plus 0,59 € par kilomètre parcouru.</li>
    </ul>

    <h2>4. Livraison</h2>
    <p>La commande est livrée à l'adresse, à la date et à l'heure indiquées par le client.
       Le client s'assure qu'une personne est présente pour la réception.</p>

    <h2>5. Annulation</h2>
    <p>Le client peut annuler sa commande depuis son espace tant qu'elle n'a pas été acceptée par notre équipe.
       Une fois acceptée, la commande ne peut plus être annulée par le client : il doit nous contacter.</p>
    <p>Vite &amp; Gourmand peut annuler une commande après avoir contacté le client (par téléphone ou email),
       en lui indiquant le motif de l'annulation.</p>

    <h2>6. Prêt de matériel</h2>
    <p>Certains menus comprennent le prêt de matériel (plateaux, chafing dishes, nappage).
       Il doit être restitué dans un délai de <strong>10 jours ouvrés</strong> après la prestation.
       Passé ce délai, des <strong>frais de 600 €</strong> sont facturés au client.</p>

    <h2>7. Avis</h2>
    <p>Une fois la commande terminée, le client peut laisser une note et un commentaire.
       Les avis sont relus par notre équipe avant d'être publiés.</p>

